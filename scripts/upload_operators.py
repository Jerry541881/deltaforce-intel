def load_config():
    if not os.path.exists(CONFIG_PATH):
        print("找不到配置文件：%s" % CONFIG_PATH)
        print("请把本脚本放在 D:\\deltaforce-intel\\scripts\\ 下运行")
        sys.exit(1)
    with open(CONFIG_PATH, encoding="utf-8") as f:
        return json.load(f)


def main():
    cfg = load_config()
    url = cfg["url"].rstrip("/")
    key = cfg["key"]

    try:
        import requests
    except ImportError:
        print("缺少 requests 库，请先执行：pip install requests")
        sys.exit(1)

    endpoint = url + "/rest/v1/operators"
    headers = {
        "apikey": key,
        "Authorization": "Bearer " + key,
        "Content-Type": "application/json",
        "Prefer": "resolution=merge-duplicates,return=minimal",
    }

    payload = []
    for (code, real_name, role, tier, position, skills,
         playstyle, pros, cons, weapons, difficulty) in DATA:
        payload.append({
            "code": code,
            "real_name": real_name,
            "role": role,
            "tier": tier,
            "position": position,
            "skills": skills,
            "playstyle": playstyle,
            "pros": pros,
            "cons": cons,
            "weapons": weapons,
            "difficulty": difficulty,
            "season": SEASON,
            "source": SOURCE,
        })

    print("待上传干员：%d 名" % len(payload))

    r = requests.post(endpoint + "?on_conflict=code",
                      headers=headers, json=payload, timeout=60)

    if r.status_code in (200, 201, 204):
        print("上传成功：共 %d 名干员" % len(payload))
        roles = {}
        tiers = {}
        for p in payload:
            roles[p["role"]] = roles.get(p["role"], 0) + 1
            tiers[p["tier"]] = tiers.get(p["tier"], 0) + 1
        print("--- 按兵种 ---")
        for k in sorted(roles, key=lambda x: -roles[x]):
            print("  %s: %d" % (k, roles[k]))
        print("--- 按梯队 ---")
        for k in sorted(tiers):
            print("  %s: %d" % (k, tiers[k]))
        return True

    print("上传失败 HTTP %s" % r.status_code)
    print(r.text[:500])
    return False


if __name__ == "__main__":
    ok = main()
    sys.exit(0 if ok else 1)
