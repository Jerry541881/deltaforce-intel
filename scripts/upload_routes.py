def load_config():
    if not os.path.exists(CONFIG_PATH):
        print("找不到配置文件：%s" % CONFIG_PATH)
        print("请把本脚本放在 D:\\deltaforce-intel\\scripts\\ 下运行")
        sys.exit(1)
    with open(CONFIG_PATH, encoding="utf-8") as f:
        return json.load(f)


def main():
    cfg = load_config()
    url = cfg["url"].rstrip("/")
    key = cfg["key"]

    try:
        import requests
    except ImportError:
        print("缺少 requests 库，请先执行：pip install requests")
        sys.exit(1)

    endpoint = url + "/rest/v1/routes"
    headers = {
        "apikey": key,
        "Authorization": "Bearer " + key,
        "Content-Type": "application/json",
        "Prefer": "resolution=merge-duplicates,return=minimal",
    }

    payload = []
    for (map_name, level, name, spawn, path, spots,
         extract, est_time, est_value, risk, operator, loadout, tips) in DATA:
        payload.append({
            "map_name": map_name,
            "level": level,
            "name": name,
            "spawn": spawn,
            "path": path,
            "spots": spots,
            "extract": extract,
            "est_time": est_time,
            "est_value": est_value,
            "risk": risk,
            "operator": operator,
            "loadout": loadout,
            "tips": tips,
            "season": SEASON,
            "source": SOURCE,
        })

    print("待上传路线：%d 条" % len(payload))

    r = requests.post(endpoint + "?on_conflict=map_name,name",
                      headers=headers, json=payload, timeout=60)

    if r.status_code in (200, 201, 204):
        print("上传成功：共 %d 条路线" % len(payload))
        maps = {}
        for p in payload:
            maps[p["map_name"]] = maps.get(p["map_name"], 0) + 1
        print("--- 按地图 ---")
        for k in sorted(maps, key=lambda x: -maps[x]):
            print("  %s: %d 条" % (k, maps[k]))
        return True

    print("上传失败 HTTP %s" % r.status_code)
    print(r.text[:500])
    return False


if __name__ == "__main__":
    ok = main()
    sys.exit(0 if ok else 1)
